/**
 * The emoji the picker offers, as `[glyph, search words]`.
 *
 * Curated rather than the full Unicode set: the complete list is ~1,900
 * glyphs, most of which nobody has ever sent, and shipping it (with the names
 * needed to make search work) would be tens of kilobytes of JS parsed on
 * every cold start for a sheet that opens occasionally. This is the part of it
 * people actually use, grouped the way every keyboard groups it, and search
 * covers the names rather than only the exact word.
 *
 * Skin tones are left off deliberately: a tone modifier turns one chip into
 * six, and a reaction bar is not the place to make that choice. The neutral
 * form is what gets stored, so nothing here can go stale against the database
 * — `chat_reactions.emoji` is free text.
 */

