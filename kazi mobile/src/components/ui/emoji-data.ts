/** Flat search across every group, matched on the glyph's own words. */
export function searchEmoji(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const out: string[] = [];
  for (const group of EMOJI_GROUPS) {
    for (const [glyph, words] of group.emoji) {
      if (words.includes(q) && !out.includes(glyph)) out.push(glyph);
    }
  }
  return out;
}
