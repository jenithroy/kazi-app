    const design = makeDesign(seed * 7919 + cfg.id.length, { colors: 1 + (seed % 5), longStitches: cfg.long, plainJumps: cfg.plain });
    if (cfg.id === "xxx" && hasXxxLongForm(design)) continue; // see the XXX note near the end
