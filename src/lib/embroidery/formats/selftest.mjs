// 2. Round trips

function makeRandom(seed) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13;
    s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5;
    s >>>= 0;
    return s / 4294967296;
  };
}

/**
 * A random design: colour blocks of stitches, islands joined by a TRIM (and, if `plainJumps`, a JUMP), some long stitches.
 * `longStitches` adds stitches over 12.1 mm that a format has to cut up; `plainJumps` adds jumps that follow no trim.
 */
function makeDesign(seed, { colors, longStitches, plainJumps }) {
  const rand = makeRandom(seed);
  const threads = [];
  const st = [];
  let x = Math.round((rand() - 0.5) * 600);
  let y = Math.round((rand() - 0.5) * 600);
  for (let b = 0; b < colors; b++) {
    threads.push({ r: Math.floor(rand() * 256), g: Math.floor(rand() * 256), b: Math.floor(rand() * 256), name: `Thread ${b + 1}` });
    if (b > 0) st.push([x, y, CMD.COLOR_CHANGE]);
    const islands = 1 + Math.floor(rand() * 3);
    for (let isl = 0; isl < islands; isl++) {
      if (isl > 0 || b > 0) {
        if (isl > 0) st.push([x, y, CMD.TRIM]);
        const far = rand() < 0.3 ? 900 : 120;
        x = Math.round(x + (rand() - 0.5) * far);
        y = Math.round(y + (rand() - 0.5) * far);
        if (plainJumps || isl > 0) st.push([x, y, CMD.JUMP]);
      }
      const count = 5 + Math.floor(rand() * 25);
      for (let i = 0; i < count; i++) {
        const long = longStitches && rand() < 0.06;
        const step = long ? 130 + rand() * 170 : 1 + rand() * 60;
        const a = rand() * Math.PI * 2;
        x = Math.round(x + Math.cos(a) * step);
        y = Math.round(y + Math.sin(a) * step);
        st.push([x, y, CMD.STITCH]);
        if (plainJumps && rand() < 0.05) {
          x += Math.round((rand() - 0.5) * 80);
          y += Math.round((rand() - 0.5) * 80);
          st.push([x, y, CMD.JUMP]);
        }
      }
    }
  }
  st.push([x, y, CMD.END]);
  return { name: `Design ${seed}`, threads, stitches: st };
}

/** Does the design have a stitch of exactly 12.4 mm in x or y once cut for XXX? XXX stores such a stitch as a long stitch, which its reader returns as a jump. */
function hasXxxLongForm(design) {
  const { stitches } = normalizePattern(design, { maxJump: 124, maxStitch: 124, fullJump: false, round: true });
  let xx = 0;
  let yy = 0;
  for (const s of stitches) {
    const dx = pyInt(pyRound(s[0] - xx));
    const dy = pyInt(pyRound(s[1] - yy));
    xx += dx;
    yy += dy;
    if (s[2] === CMD.STITCH && (Math.abs(dx) >= 124 || Math.abs(dy) >= 124)) return true;
  }
  return false;
}

/** The needle points (x, y, colour block) of a stitch list, and how many trims it has. */
function needlePoints(stitches) {
  const pts = [];
  let block = 0;
  let trims = 0;
  let started = false;
  for (const [x, y, c] of stitches) {
    if (c === CMD.END) break;
    if (c === CMD.STITCH) {
      started = true;
      pts.push([x, y, block]);
    } else if (c === CMD.COLOR_CHANGE) {
      if (started) block++;
      started = true;
    } else if (c === CMD.TRIM) trims++;
  }
  return { pts, trims };
}

