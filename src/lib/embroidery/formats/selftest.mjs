let goldenWriteOk = 0;
let goldenReadOk = 0;
for (const g of GOLDEN) {
  const want = unpack(g.bytes);
  const label = `${g.pattern} as ${g.variant}`;
  const got = writePattern(g.format, GOLDEN_PATTERNS[g.pattern], g.write);
  let first = -1;
  for (let i = 0; i < Math.max(got.length, want.length); i++) {
    if (got[i] !== want[i]) {
      first = i;
      break;
    }
  }
  check(`golden bytes, ${label}`, first === -1, `first different byte at offset ${first}, sizes ${got.length} and ${want.length}`);
  if (first === -1) goldenWriteOk++;

  const read = readPattern(g.format, want, g.read);
  const stitchesOk = JSON.stringify(read.stitches) === JSON.stringify(g.stitches);
  check(`golden read, stitches, ${label}`, stitchesOk, `got ${JSON.stringify(read.stitches).slice(0, 200)}`);
  let threadsOk = true;
  if (g.threads === null) {
    threadsOk = read.colorsFromFile === false;
  } else if (g.threads.length > 0) {
    // a format that stores a STOP like a colour change lists fewer threads than it has colour blocks: the rest are stand-ins
    const mine = read.threads.slice(0, g.threads.length).map((t) => [t.r, t.g, t.b, t.name || null, t.code || null, t.brand || null]);
    threadsOk = JSON.stringify(mine) === JSON.stringify(g.threads) && read.colorsFromFile === (g.threads.length >= read.threads.length);
  }
  check(`golden read, threads, ${label}`, threadsOk, `got ${JSON.stringify(read.threads).slice(0, 200)}`);
  if (stitchesOk && threadsOk) goldenReadOk++;
}

