/**
 * Self-test for the embroidery file writers and readers. No Python, no network, no test runner:
 *
 *     node src/lib/embroidery/formats/selftest.mjs
 *
 * It prints one line, and exits with code 1 if anything failed (the failures are listed above that line).
 *
 * WHAT IT CHECKS
 *   1. GOLDEN FILES. A few small designs were written by pyembroidery 1.5.1 in every format (the data block below, packed).
 *      Our writer must give the very same bytes, and our reader must read pyembroidery's bytes the way pyembroidery's own
 *      reader does. The same was checked, with scripts that need Python, on 1 781 other designs in 18 format variants
 *      (32 058 files: 30 673 identical byte for byte; the other 1 385 are designs where pyembroidery itself invents a random
 *      thread, stops with an error, or writes a DST header that overflows). These few are the part anyone can repeat.
 *   2. ROUND TRIPS. Random designs are written and read back by our own code: the needle must land where the design said, in
 *      the same colour block; trims must survive where the format can say them; threads must keep their colour where the
 *      format stores it.
 *   3. DETAILS. Rounding (Python rounds halves to even), the thread tables, Python's set order, the header of DST, needle
 *      numbers, JEF date, options, empty designs, bad input, damaged files.
 */
