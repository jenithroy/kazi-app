let passed = 0;
const failures = [];
const check = (name, ok, detail) => {
  if (ok) passed++;
  else failures.push(detail === undefined ? name : `${name}: ${detail}`);
};
const eq = (name, got, want) => {
  const a = String(JSON.stringify(got));
  const b = String(JSON.stringify(want));
  check(name, a === b, `expected ${b.length > 160 ? b.slice(0, 160) + "..." : b}, got ${a.length > 160 ? a.slice(0, 160) + "..." : a}`);
};
const throwsError = (name, fn, pattern) => {
  try {
    fn();
    check(name, false, "did not throw");
  } catch (e) {
    check(name, e instanceof Error && pattern.test(e.message), `threw "${e && e.message}"`);
  }
};

/** Bytes from the packed form: "hh" is a byte, "hh*n" is that byte n times. */
function unpack(lines) {
  const out = [];
  for (const line of lines) {
    for (const tok of line.split(" ")) {
      if (!tok) continue;
      const star = tok.indexOf("*");
      if (star < 0) out.push(parseInt(tok, 16));
      else for (let i = 0, n = Number(tok.slice(star + 1)); i < n; i++) out.push(parseInt(tok.slice(0, star), 16));
    }
  }
  return Uint8Array.from(out);
}

